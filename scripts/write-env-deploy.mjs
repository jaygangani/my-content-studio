#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const outputsPath = join(appRoot, 'cdk-outputs.json')
const envDeployPath = join(appRoot, '.env.deploy')

if (!existsSync(outputsPath)) {
  console.error(`Missing ${outputsPath}. Run npm run infra:deploy first.`)
  process.exit(1)
}

const outputs = JSON.parse(readFileSync(outputsPath, 'utf8'))
const hosting = outputs.MyContentStudioWebHosting
if (!hosting?.BucketName || !hosting?.DistributionId) {
  console.error('cdk-outputs.json missing MyContentStudioWebHosting BucketName / DistributionId')
  console.error(JSON.stringify(outputs, null, 2))
  process.exit(1)
}

function readEnvValue(path, key) {
  if (!existsSync(path)) return undefined
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eq = trimmed.indexOf('=')
    if (eq <= 0) continue
    if (trimmed.slice(0, eq).trim() !== key) continue
    let value = trimmed.slice(eq + 1).trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    return value
  }
  return undefined
}

const keep = ['CDK_DEFAULT_ACCOUNT', 'APP_DOMAIN', 'APP_CERTIFICATE_ARN']
const region = process.env.AWS_REGION || process.env.CDK_DEFAULT_REGION || 'ap-south-1'
const lines = ['# Generated by npm run infra:deploy. Do not commit.', '']

for (const key of keep) {
  const value = process.env[key] || readEnvValue(envDeployPath, key)
  if (value) lines.push(`${key}=${value}`)
}

lines.push(
  '',
  `S3_BUCKET=${hosting.BucketName}`,
  `CLOUDFRONT_DISTRIBUTION_ID=${hosting.DistributionId}`,
  `AWS_REGION=${region}`,
  `APP_URL=${hosting.AppUrl}`,
  '',
  '# Optional:',
  '# S3_PREFIX=',
  '# SKIP_BUILD=0',
  '# DRY_RUN=0',
  '',
)

writeFileSync(envDeployPath, lines.join('\n'), 'utf8')
console.log(`Wrote ${envDeployPath}`)
console.log(`  S3_BUCKET=${hosting.BucketName}`)
console.log(`  CLOUDFRONT_DISTRIBUTION_ID=${hosting.DistributionId}`)
console.log(`  APP_URL=${hosting.AppUrl}`)
if (hosting.DistributionDomainName) {
  console.log(`  CloudFront domain: ${hosting.DistributionDomainName}`)
}
